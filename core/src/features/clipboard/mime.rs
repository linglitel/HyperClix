pub(super) fn code(mime: &str) -> u8 {
    MIME_TYPES
        .iter()
        .position(|value| *value == mime)
        .unwrap_or(0) as u8
}

pub(super) fn name(code: u8) -> &'static str {
    MIME_TYPES
        .get(code as usize)
        .copied()
        .unwrap_or("application/octet-stream")
}
